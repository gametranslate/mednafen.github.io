(async()=>{
 const invoke=(command,args={})=>window.__TAURI_INTERNALS__.invoke(command,args);
 const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
 const assert=(value,label)=>{if(!value)throw new Error(label);};
 const wait=async(test,label,timeout=25000)=>{const deadline=performance.now()+timeout;while(performance.now()<deadline){if(await test())return;await delay(80);}throw new Error('Timed out: '+label);};
 const buttons=name=>[...document.querySelectorAll('button')].filter(b=>b.textContent.trim()===name);
 const click=async name=>{await wait(()=>buttons(name).some(b=>!b.disabled),'button '+name);buttons(name).findLast(b=>!b.disabled).click();};
 const event=(code,down,shift=false)=>window.dispatchEvent(new KeyboardEvent(down?'keydown':'keyup',{code,key:code,shiftKey:shift,bubbles:true,cancelable:true}));
 const press=async(code,shift=false)=>{event(code,true,shift);await delay(110);event(code,false,shift);await delay(100);};
 const samples=[],checks=[],errors=[];
 window.addEventListener('error',e=>errors.push(e.message));
 window.addEventListener('unhandledrejection',e=>errors.push(String(e.reason)));
 try{
  await wait(()=>window.__TAURI_INTERNALS__ && document.querySelector('.app-shell'),'frontend ready');
  const context=await invoke('qa_context');
  await invoke('save_settings',{scope:null,values:{sound:'1','sound.driver':'sdl','sound.volume':'0','filesys.state_comp_level':'0','video.driver':context.driver,'video.glvsync':'0','wswan.xscale':'2','wswan.yscale':'2'},preferences:null});
  const store=await invoke('add_games',{paths:[context.rom]});
  const game=store.games[0];
  await wait(()=>document.querySelector('.play-button:not(:disabled)'),'library refresh');
  document.querySelector('.play-button').click();
  await wait(async()=>{const s=await invoke('player_status');return s.ready&&s.transport==='canvas'&&Number(document.querySelector('[data-testid=game-canvas]')?.dataset.frame)>0;},'first canvas frame');
  await wait(()=>!document.querySelector('[data-testid=player-viewport] [role=status]'),'startup complete');
  await delay(2500);
  const canvas=document.querySelector('[data-testid=game-canvas]');
  const rgba=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
  const colors=new Set();for(let i=0;i<rgba.length;i+=4)colors.add((rgba[i]<<16)|(rgba[i+1]<<8)|rgba[i+2]);
  assert(colors.size>4,'Game canvas is blank');checks.push('actual-canvas-pixels');
  const pid=(await invoke('qa_probe',{slot:0})).pid;
  const save=async(slot,label)=>{
   const before=(await invoke('qa_probe',{slot})).hash;
   await press('F1');
   await wait(async()=>{const p=await invoke('qa_probe',{slot});return p.hash&&p.hash!==before;},'save slot '+slot);
   const probe=await invoke('qa_probe',{slot,checkpoint:label});samples.push({label,time:performance.now()/1000,hash:probe.hash});
  };
  const focused=document.querySelector('.header-log');focused.focus();
  await save(0,'normal-start');await delay(1500);await save(0,'normal-end');
  assert(event('Tab',true)===false,'Tab was not captured by gameplay');
  await save(0,'fast-start');await delay(1500);await save(0,'fast-end');
  assert(document.activeElement===focused,'Tab navigated HTML buttons');event('Tab',false);await delay(300);
  await save(0,'released-start');await delay(1500);await save(0,'released-end');
  checks.push('tab-no-ui-navigation','tab-keyup');
  await press('F3');assert(!(await invoke('qa_probe',{slot:1})).hash,'Slot switch saved automatically');
  await save(1,'slot1');await delay(2000);await press('F2');await save(1,'loaded-slot1');
  await press('F3');await save(2,'slot2');await press('F3',true);await save(1,'previous-slot');
  checks.push('F1-save','F2-load','F3-next','Shift-F3-previous');
  event('Tab',true);window.dispatchEvent(new Event('blur'));await delay(300);
  await save(1,'blur-start');await delay(1500);await save(1,'blur-end');checks.push('blur-release');
  await click('Fullscreen');
  await wait(async()=>document.querySelector('.player-fullscreen')&&(await invoke('qa_probe',{slot:0})).fullscreen,'native fullscreen');
  assert(getComputedStyle(document.querySelector('.sidebar')).display==='none','Sidebar remains in fullscreen');
  await press('Escape');
  await wait(async()=>!document.querySelector('.player-fullscreen')&&!(await invoke('qa_probe',{slot:0})).fullscreen,'Esc restores window');
  assert((await invoke('qa_probe',{slot:0})).pid===pid,'Fullscreen restarted the game');
  await press('Escape');await wait(()=>document.querySelector('.library-view'),'Esc menu');
  assert((await invoke('load_snapshot')).running===game.id,'Esc stopped the game');
  await click('Now playing');await wait(()=>Number(document.querySelector('[data-testid=game-canvas]')?.dataset.frame)>0,'resume canvas');
  checks.push('fullscreen-game-only','Esc-windowed','Esc-menu','resume-same-session');
  await click('Stop game');await wait(async()=>!(await invoke('load_snapshot')).running,'stop');
  await wait(()=>document.querySelector('.play-button:not(:disabled)'),'replay ready');document.querySelector('.play-button').click();
  await wait(async()=>(await invoke('player_status')).ready&&Number(document.querySelector('[data-testid=game-canvas]')?.dataset.frame)>0,'replay');
  const replayPid=(await invoke('qa_probe',{slot:0})).pid;assert(pid!==replayPid,'Replay reused stopped process');
  assert(errors.length===0,errors.join('\n'));checks.push('stop-replay','no-console-errors');
  await invoke('qa_report',{report:{status:'PASS',driver:context.driver,pid,replayPid,colors:colors.size,canvas:{width:canvas.width,height:canvas.height},checks,samples,errors}});
  await invoke('quit_app');
 }catch(error){
  await invoke('qa_report',{report:{status:'FAIL',error:String(error),stack:error.stack,checks,samples,errors,log:await invoke('get_log').catch(()=>''),body:document.body.innerText.slice(-4000)}});
  await invoke('quit_app').catch(()=>{});
 }
})();
