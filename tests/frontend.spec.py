from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1240,'height':900})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:1420/?demo=1',wait_until='networkidle')
    expect(page.locator('.brand-footer')).to_have_attribute('href','https://gametranslate.us')
    expect(page.locator('.brand-footer img')).to_be_visible()
    expect(page.get_by_role('heading',name='Your library',exact=True)).to_be_visible()
    expect(page.locator('[data-testid="language-select"]')).to_have_value('en')
    page.locator('[data-testid="theme-toggle"]').click()
    expect(page.locator('html')).to_have_attribute('data-theme','dark')
    page.reload(wait_until='networkidle')
    expect(page.locator('html')).to_have_attribute('data-theme','dark')
    page.locator('[data-testid="theme-toggle"]').click()
    page.get_by_role('button',name='About',exact=True).click()
    expect(page.locator('.about-support a')).to_have_attribute('href','https://github.com/mednafen/mednafen.github.io')
    expect(page.locator('.credits-list article')).to_have_count(5)
    for lang in ['en','de','vi','fr','es','it','ko','zh-TW','zh-CN','ja']:
        page.locator('[data-testid="language-select"]').select_option(lang)
        expect(page.locator('html')).to_have_attribute('lang',lang)
        assert page.locator('.main-scroll h1').inner_text().strip()
        page.reload(wait_until='networkidle')
        expect(page.locator('[data-testid="language-select"]')).to_have_value(lang)
        assert not page.evaluate('document.documentElement.scrollWidth>window.innerWidth')
    page.locator('[data-testid="language-select"]').select_option('vi')
    page.screenshot(path=str(ROOT/'.cache/library.png'),full_page=True)
    page.get_by_role('button',name='Cài đặt',exact=True).click()
    page.get_by_role('button',name='Âm thanh',exact=True).click()
    volume=page.locator('[data-setting="sound.volume"] input')
    volume.fill('999')
    expect(page.get_by_role('button',name='Lưu cài đặt',exact=True)).to_be_disabled()
    expect(page.locator('[data-setting="sound.volume"] .field-error')).to_be_visible()
    volume.fill('75')
    page.get_by_role('button',name='Lưu cài đặt',exact=True).click()
    expect(page.get_by_role('button',name='Lưu cài đặt',exact=True)).to_be_disabled()
    page.get_by_label('Áp dụng cho',exact=True).select_option('sample-0')
    expect(volume).to_have_value('75')
    volume.fill('60')
    page.get_by_role('button',name='Lưu cài đặt',exact=True).click()
    expect(volume).to_have_value('60')
    page.get_by_role('button',name='Khôi phục Âm lượng (%)',exact=True).click()
    expect(volume).to_have_value('75')
    page.get_by_role('button',name='Hủy thay đổi',exact=True).click()
    expect(volume).to_have_value('60')
    page.get_by_label('Áp dụng cho',exact=True).select_option('global')
    expect(volume).to_have_value('75')
    page.screenshot(path=str(ROOT/'.cache/settings-audio.png'),full_page=True)
    page.get_by_label('Tìm cài đặt',exact=True).fill('bios_jp')
    expect(page.locator('[data-setting="psx.bios_jp"]')).to_be_visible()
    page.get_by_label('Tìm cài đặt',exact=True).fill('')
    page.get_by_role('button',name='Hình ảnh',exact=True).click()
    page.screenshot(path=str(ROOT/'.cache/settings-video.png'),full_page=True)
    page.get_by_role('button',name='Điều khiển',exact=True).click()
    page.locator('[data-setting="command.save_state"] .mapping-button').click()
    page.keyboard.press('F4')
    expect(page.locator('[data-setting="command.save_state"] .mapping-button')).to_contain_text('F4')
    page.get_by_role('button',name='Hủy thay đổi',exact=True).click()
    page.get_by_role('button',name='Tất cả thiết lập',exact=True).click()
    expect(page.locator('.fields .setting-row')).to_have_count(40)
    page.get_by_label('Tìm cài đặt',exact=True).fill('affinity.emu')
    page.locator('[data-setting="affinity.emu"] input').fill('18446744073709551616')
    expect(page.get_by_role('button',name='Lưu cài đặt',exact=True)).to_be_disabled()
    page.get_by_role('button',name='Hủy thay đổi',exact=True).click()
    page.get_by_label('Tìm cài đặt',exact=True).fill('')
    page.get_by_role('button',name='Âm thanh',exact=True).click()
    volume.fill('40')
    page.get_by_role('button',name='Tất cả game',exact=False).click()
    expect(page.get_by_role('dialog',name='Thay đổi chưa được lưu')).to_be_visible()
    page.get_by_role('button',name='Tiếp tục chỉnh sửa',exact=True).click()
    page.get_by_role('button',name='Hủy thay đổi',exact=True).click()
    for name in ['Chung','Hình ảnh','Âm thanh','Điều khiển','BIOS & firmware','Lưu game','Thư mục','Theo hệ máy','Chơi qua mạng','Tất cả thiết lập']:
        page.locator('.settings-nav').get_by_role('button',name=name,exact=True).click()
        assert page.locator('.settings-panel').is_visible()
    page.locator('.settings-nav').get_by_role('button',name='Chung',exact=True).click()
    page.locator('#app-theme').select_option('dark')
    expect(page.locator('html')).to_have_attribute('data-theme','dark')
    page.locator('.settings-nav').get_by_role('button',name='Hình ảnh',exact=True).click()
    page.screenshot(path=str(ROOT/'.cache/settings-dark.png'),full_page=True)
    for width in [1024,860,736,390]:
        page.set_viewport_size({'width':width,'height':900})
        page.screenshot(path=str(ROOT/f'.cache/settings-{width}.png'),full_page=True)
        overflow=page.evaluate('document.documentElement.scrollWidth>window.innerWidth')
        assert not overflow, f'Horizontal overflow at {width}'
    assert errors==[],errors
    print(json.dumps({'frontend':'PASS','categories':10,'responsiveWidths':[1240,1024,860,736,390],'consoleErrors':errors}))
    browser.close()
